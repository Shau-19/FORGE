def handle_scaffold(body: dict) -> dict:
    name      = body.get('name', 'forge-project').strip() or 'forge-project'
    stack     = body.get('stack', [])
    structure = body.get('structure', 'monorepo')
    prd       = body.get('prd', {})
    idea      = body.get('idea', '')
    gh_token  = body.get('github_token', '')
    private   = body.get('private', False)

    prd_overview = prd.get('overview', '') if isinstance(prd, dict) else ''

    # ── LLM: generate scaffold ──────────────────────────────────────────────
    system, user = prompts.generate_scaffold(idea, stack, structure, prd_overview)
    result = llm.call(prompt=user, system=system, max_tokens=2500)

    try:
        parsed = _parse_json(result['text'])
    except json.JSONDecodeError as e:
        raise RuntimeError(f'LLM returned invalid JSON: {e}')

    files  = parsed.get('files', [])
    readme = parsed.get('readme', '')
    docker = parsed.get('docker_compose', '')

    # ── VALIDATE + NORMALIZE before CI selection ────────────────────────────
    files = _validate_scaffold(files, stack)

    # ── CI template: file-based detection (not stack guessing) ──────────────
    gh_actions = get_ci_template(stack, files)

    # Add README, docker-compose, CI workflow
    extra_files = []
    existing_paths = {f['path'] for f in files}

    if readme and 'README.md' not in existing_paths:
        extra_files.append({'type': 'file', 'path': 'README.md', 'content': readme})
    if docker and 'docker-compose.yml' not in existing_paths:
        extra_files.append({'type': 'file', 'path': 'docker-compose.yml', 'content': docker})
    if gh_actions:
        extra_files.append({'type': 'dir',  'path': '.github/'})
        extra_files.append({'type': 'dir',  'path': '.github/workflows/'})
        extra_files.append({'type': 'file', 'path': '.github/workflows/ci.yml', 'content': gh_actions})

    all_files = files + extra_files
    repo_url  = f'https://github.com/user/{name}'
    pushed    = 0

    # ── GitHub: create repo + push files ────────────────────────────────────
    if gh_token:
        try:
            repo_info = _github_create_repo(gh_token, name, private)
            repo_full = repo_info.get('full_name', f'user/{name}')
            repo_url  = repo_info.get('html_url', repo_url)

            workflow_files = [f for f in all_files if '.github' in f.get('path', '')]
            src_files      = [f for f in all_files if '.github' not in f.get('path', '')]

            src_pushed = 0
            for f in src_files:
                if f['type'] == 'file' and f.get('content', '').strip():
                    _github_push_file(gh_token, repo_full, f['path'], f['content'])
                    print(f'  [GitHub] pushed: {f["path"]}')
                    src_pushed += 1

            wf_pushed = 0
            for f in workflow_files:
                if f['type'] == 'file' and f.get('content', '').strip():
                    _github_push_file(gh_token, repo_full, f['path'], f['content'])
                    print(f'  [GitHub] pushed workflow: {f["path"]}')
                    wf_pushed += 1

            print(f'  [GitHub] repo created/found: {repo_url}')
            print(f'  [GitHub] pushing {src_pushed} files + {wf_pushed} workflow files...')
            pushed = src_pushed + wf_pushed

        except RuntimeError as e:
            return {
                'files':        all_files, 'repo_url': '',
                'pushed':       0,         'github_error': str(e),
                'tokens_used':  result['tokens_used'], 'model': result['model'],
                'provider':     result['provider'],    'latency_ms': result['latency_ms'],
            }

    return {
        'files':       all_files,  'repo_url':    repo_url,
        'pushed':      pushed,     'tokens_used': result['tokens_used'],
        'model':       result['model'], 'provider': result['provider'],
        'latency_ms':  result['latency_ms'],
    }