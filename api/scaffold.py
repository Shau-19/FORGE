def _parse_json(text: str) -> dict:
    import re
    text = text.strip()
    if text.startswith('```'):
        lines = text.split('\n')
        text = '\n'.join(lines[1:-1] if lines[-1].strip() == '```' else lines[1:])
    text = text.strip()
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    def sanitize_json_strings(s: str) -> str:
        result = []
        in_string = False
        i = 0
        while i < len(s):
            c = s[i]
            if c == '\\' and in_string:
                result.append(c)
                if i + 1 < len(s):
                    result.append(s[i + 1])
                    i += 2
                    continue
            elif c == '"':
                in_string = not in_string
                result.append(c)
            elif in_string:
                if c == '\n':   result.append('\\n')
                elif c == '\r': result.append('\\r')
                elif c == '\t': result.append('\\t')
                elif ord(c) < 32: result.append(f'\\u{ord(c):04x}')
                else: result.append(c)
            else:
                result.append(c)
            i += 1
        return ''.join(result)

    try:
        return json.loads(sanitize_json_strings(text))
    except json.JSONDecodeError:
        pass

    start = text.find('{')
    end   = text.rfind('}')
    if start != -1 and end != -1:
        try:
            return json.loads(sanitize_json_strings(text[start:end+1]))
        except json.JSONDecodeError:
            pass

    raise json.JSONDecodeError('Could not parse LLM scaffold response', text, 0)


def _github_create_repo(token: str, name: str, private: bool = False) -> dict:
    data = json.dumps({
        'name': name, 'private': private,
        'auto_init': False, 'description': 'Generated by FORGE',
    }).encode()
    req = urllib.request.Request(
        'https://api.github.com/user/repos', data=data,
        headers={'Authorization': f'token {token}', 'Accept': 'application/vnd.github+json',
                 'Content-Type': 'application/json', 'X-GitHub-Api-Version': '2022-11-28'},
        method='POST',
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        body = e.read().decode()
        raise RuntimeError(f'GitHub repo creation failed ({e.code}): {body[:200]}')


def _github_push_file(token: str, repo_full: str, path: str, content: str,
                      message: str = 'Initial scaffold by FORGE'):
    encoded = base64.b64encode(content.encode()).decode()
    data = json.dumps({'message': message, 'content': encoded}).encode()
    url = f'https://api.github.com/repos/{repo_full}/contents/{path}'
    req = urllib.request.Request(
        url, data=data,
        headers={'Authorization': f'token {token}', 'Accept': 'application/vnd.github+json',
                 'Content-Type': 'application/json'},
        method='PUT',
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        if e.code == 422:
            return {}
        raise RuntimeError(f'GitHub push failed for {path} ({e.code}): {e.read().decode()[:100]}')


