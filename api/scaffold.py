def _detect_project_type(files: list, stack: list) -> str:
    """
    Determine project type from ACTUAL generated files.
    Returns: 'python', 'node', 'fullstack'
    """
    paths = {f['path'] for f in files if f.get('type') == 'file'}
    has_py = any(p.endswith('.py') for p in paths)

    # Detect any JS/React signal — including misplaced files like app/index.js
    has_js = any(
        p.endswith(('.js', '.jsx', '.tsx', '.ts'))
        and not any(p.startswith(d) for d in _BACKEND_DIRS)
        for p in paths
    )

    # Stack keywords as secondary signal
    stack_lower = ' '.join(s.lower() for s in stack)
    stack_has_react  = any(k in stack_lower for k in {'react', 'vue', 'angular', 'nextjs', 'next.js'})
    stack_has_python = any(k in stack_lower for k in {'fastapi', 'flask', 'django', 'python'})
    stack_has_node   = any(k in stack_lower for k in {'node', 'express', 'node.js', 'express.js'})

    # Fullstack: Python+React OR Node+React (any backend + React frontend)
    has_backend = has_py or stack_has_python or has_js or stack_has_node
    has_frontend = stack_has_react or any('frontend/' in f.get('path','') for f in files if isinstance(f, dict))

    if stack_has_react and (has_py or stack_has_python):
        return 'fullstack'   # Python + React
    if stack_has_react and (has_js or stack_has_node):
        return 'fullstack'   # Node + React
    if has_py or stack_has_python:
        return 'python'
    if has_js or stack_has_node:
        return 'node'
    return 'python'  # safe default


def _validate_scaffold(files: list, stack: list) -> list:
    """
    Enforce mandatory skeleton per project type.
    1. Detect project type from files + stack
    2. Move misplaced frontend JS files → frontend/src/
    3. Guarantee all skeleton files exist (inject defaults if missing)
    LLM-generated content is kept; only missing files are injected.
    """
    project_type = _detect_project_type(files, stack)
    print(f'  [SCAFFOLD] project type: {project_type}')

    if project_type != 'fullstack':
        # Python-only: no frontend normalization needed
        paths = {f['path'] for f in files if f.get('type') == 'file'}
        print(f'  [SCAFFOLD] {project_type}: {len(paths)} files — no normalization needed')
        return files

    # ── FULLSTACK normalization ──────────────────────────────────────────────

    # Step 1: Move any misplaced frontend JS files → frontend/src/
    normalized = []
    for f in files:
        fpath = f.get('path', '')
        if (f.get('type') == 'file'
                and fpath.endswith(('.js', '.jsx', '.tsx', '.css', '.ts'))
                and not fpath.startswith('frontend/')
                and not any(fpath.startswith(d) for d in _BACKEND_DIRS)):
            new_path = 'frontend/src/' + fpath.split('/')[-1]
            print(f'  [SCAFFOLD] moved: {fpath} → {new_path}')
            f = dict(f, path=new_path)
        normalized.append(f)
    files = normalized

    # Step 2: Build path index after normalization
    path_map = {f['path']: f for f in files if f.get('type') == 'file'}

    # Step 3: Guarantee every frontend skeleton file exists
    for skel_path in _FULLSTACK_SKELETON_FRONTEND:
        if skel_path not in path_map:
            default_content = _SKELETON_DEFAULTS.get(skel_path, f'// {skel_path}')
            print(f'  [SCAFFOLD] injecting: {skel_path}')
            files.append({'type': 'file', 'path': skel_path, 'content': default_content})

    print(f'  [SCAFFOLD] fullstack normalized: {len(files)} files total')
    return files





